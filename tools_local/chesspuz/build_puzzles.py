#!/usr/bin/env python3
"""Pick Checkmate's bundled puzzles from the Lichess puzzle database.

    curl -LO https://database.lichess.org/lichess_db_puzzle.csv.zst
    uv run --with zstandard python tools_local/chesspuz/build_puzzles.py lichess_db_puzzle.csv.zst

Writes src/apps_local/chesspuz/ChessPuzzleData.h. The output is committed, so a
checkout builds without the 300MB download. The database is CC0
(https://database.lichess.org/#puzzles); the app credits Lichess anyway.

Kept: puzzles tagged `endgame` and `mateIn1`, `mateIn2` or `mateIn3`, that
plenty of people have played and liked, so a bad or ambiguous one is unlikely.
Each level takes PER_LEVEL of them spread evenly across its rating range, and
the device plays them easiest first.

host-tests/chesspuz replays every one through the device's own rules, so a
puzzle that ChessCore would read differently fails the suite, not the player.
"""

import argparse
import csv
import io
import os
import sys

PER_LEVEL = 250
MIN_PLAYS = 300
MIN_POPULARITY = 80
MAX_DEVIATION = 90

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "src", "apps_local", "chesspuz", "ChessPuzzleData.h")


def open_text(path):
    if path.endswith(".zst"):
        import zstandard  # noqa: PLC0415  (only needed for the compressed dump)

        raw = open(path, "rb")
        return io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(raw), encoding="utf-8")
    return open(path, encoding="utf-8", newline="")


def spread(rows, count):
    """`count` rows evenly spaced through `rows`, which is sorted by rating."""
    if len(rows) <= count:
        return rows
    step = len(rows) / count
    return [rows[int(i * step + step / 2)] for i in range(count)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv", help="lichess_db_puzzle.csv or .csv.zst")
    parser.add_argument("--per-level", type=int, default=PER_LEVEL)
    args = parser.parse_args()

    levels = {1: [], 2: [], 3: []}
    with open_text(args.csv) as f:
        reader = csv.reader(f)
        header = next(reader)
        col = {name: i for i, name in enumerate(header)}
        for row in reader:
            themes = row[col["Themes"]].split()
            if "endgame" not in themes:
                continue
            level = next((n for n in (1, 2, 3) if f"mateIn{n}" in themes), None)
            if level is None:
                continue
            if int(row[col["NbPlays"]]) < MIN_PLAYS or int(row[col["Popularity"]]) < MIN_POPULARITY:
                continue
            if int(row[col["RatingDeviation"]]) > MAX_DEVIATION:
                continue
            moves = row[col["Moves"]].split()
            if len(moves) != 2 * level:
                continue
            levels[level].append((int(row[col["Rating"]]), row[col["PuzzleId"]], row[col["FEN"]], " ".join(moves)))

    out = []
    out.append("#pragma once\n")
    out.append("// GENERATED by tools_local/chesspuz/build_puzzles.py from the Lichess puzzle")
    out.append("// database (https://database.lichess.org/#puzzles, CC0). Do not edit by hand.")
    out.append("//")
    out.append("// Endgame mates in one, two and three, easiest first. Each record is the")
    out.append("// position before the opponent's last move, then that move and the solution.\n")
    out.append('#include "ChessPuzzleCore.h"\n')
    out.append("namespace chesspuz {\n")
    for level in (1, 2, 3):
        rows = sorted(levels[level])
        picked = spread(rows, args.per_level)
        print(f"mate in {level}: {len(rows)} candidates, {len(picked)} kept", file=sys.stderr)
        out.append(f"static constexpr PuzzleRecord kMateIn{level}[] = {{")
        for rating, pid, fen, moves in picked:
            out.append(f'    {{"{pid}", "{fen}", "{moves}", {rating}}},')
        out.append("};")
    out.append("")
    out.append("struct Level {")
    out.append("  const PuzzleRecord* puzzles;")
    out.append("  int count;")
    out.append("};")
    out.append("")
    out.append("static constexpr Level kPuzzleLevels[kLevels] = {")
    for level in (1, 2, 3):
        out.append(f"    {{kMateIn{level}, static_cast<int>(sizeof(kMateIn{level}) / sizeof(PuzzleRecord))}},")
    out.append("};\n")
    out.append("}  // namespace chesspuz")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)}", file=sys.stderr)


if __name__ == "__main__":
    main()
